 const storageProbe=await page.context().newPage()
 await storageProbe.route('**/__homepage_draft_storage_probe__',route=>route.fulfill({status:200,contentType:'text/html',body:'<!doctype html><title>Storage probe</title>'}))
 await storageProbe.goto(base+'/__homepage_draft_storage_probe__')
